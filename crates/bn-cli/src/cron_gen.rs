//! Render scheduler artifacts from cron-manifest entries: systemd `.service`/`.timer` units
//! (schedules pass through verbatim — systemd parses `OnCalendar` natively) and launchd user-agent
//! plists ([`render_launchd`] translates the manifest's OnCalendar subset into
//! `StartInterval`/`StartCalendarInterval`, since launchd has no OnCalendar parser).

use bn_core::crons::ResolvedCron;
use bn_core::resolver::JobScope;

/// Unit base name (no extension). Global crons are `bn-<job>`; a repo-scoped cron carries the
/// repo so two repos' same-named crons never collide.
pub fn unit_name(rc: &ResolvedCron) -> String {
    match (&rc.scope, &rc.repo) {
        (JobScope::Global, _) | (_, None) => format!("bn-{}", rc.entry.job),
        (_, Some(repo)) => format!("bn-{}-{}", sanitize(repo), rc.entry.job),
    }
}

fn sanitize(s: &str) -> String {
    s.to_lowercase()
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '-' })
        .collect()
}

/// Render the systemd `.service` + `.timer` bodies for one cron entry. `bn_path` is the absolute
/// `bn` binary the service execs (e.g. `~/.bin/bn`). The schedule passes straight into
/// `OnCalendar=` — systemd validates it itself.
pub fn render_systemd(rc: &ResolvedCron, bn_path: &str) -> (String, String) {
    let e = &rc.entry;
    let desc = e
        .description
        .clone()
        .unwrap_or_else(|| format!("bn — {} (generated)", e.job));

    let mut service = String::from("[Unit]\n");
    service.push_str(&format!("Description={desc}\n"));
    if e.network {
        service.push_str("After=network-online.target\n");
        service.push_str("Wants=network-online.target\n");
    }
    service.push_str(
        "\n[Service]\nType=oneshot\n# Generated by `bn cron register` from a crons.toml entry. `bn run` records the\n\
         # outcome to the event log so `bn cron status` / `bn doctor` see it.\n",
    );
    service.push_str(&format!("ExecStart={bn_path} run {}\n", e.job));

    let mut timer = String::from("[Unit]\n");
    timer.push_str(&format!("Description=bn {} timer (generated)\n", e.job));
    timer.push_str("\n[Timer]\n");
    timer.push_str(&format!("OnCalendar={}\n", e.on_calendar));
    timer.push_str(&format!("Persistent={}\n", e.persistent));
    if let Some(rd) = &e.randomized_delay {
        timer.push_str(&format!("RandomizedDelaySec={rd}\n"));
    }
    timer.push_str("\n[Install]\nWantedBy=timers.target\n");

    (service, timer)
}

/// launchd label for a cron entry — `com.bn.<job>`, or `com.bn.<repo>.<job>` when repo-scoped
/// (dots separate segments; jobs/repos are sanitized to `[a-z0-9-]`, so the job is always the
/// last dot segment — [`label_job`] relies on that to invert).
pub fn launchd_label(rc: &ResolvedCron) -> String {
    match (&rc.scope, &rc.repo) {
        (JobScope::Global, _) | (_, None) => format!("com.bn.{}", sanitize(&rc.entry.job)),
        (_, Some(repo)) => format!("com.bn.{}.{}", sanitize(repo), sanitize(&rc.entry.job)),
    }
}

/// The job name a `com.bn.…` label was generated from (its last dot segment). `None` for labels
/// bn didn't generate.
pub fn label_job(label: &str) -> Option<&str> {
    label.strip_prefix("com.bn.")?.rsplit('.').next()
}

/// systemd weekday name → launchd `Weekday` integer (0 = Sunday … 6 = Saturday).
fn weekday_num(name: &str) -> Option<u8> {
    match name {
        "Sun" => Some(0),
        "Mon" => Some(1),
        "Tue" => Some(2),
        "Wed" => Some(3),
        "Thu" => Some(4),
        "Fri" => Some(5),
        "Sat" => Some(6),
        _ => None,
    }
}

/// One `StartCalendarInterval` entry. `hour: None` means "every hour" — launchd treats an omitted
/// calendar field as a wildcard, which is how a staggered minute phase like `*:15/30` (fire at
/// :15/:45 of every hour) is expressed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CalEntry {
    weekday: Option<u8>,
    hour: Option<u8>,
    minute: u8,
}

/// A manifest schedule translated for launchd: a fixed repeat interval, or calendar firings.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LaunchdSchedule {
    /// `StartInterval` seconds — for `*:0/N` (phase-0) minutely repeats.
    Interval(u64),
    /// `StartCalendarInterval` entries — for daily/weekly/hour-stepped firings and staggered
    /// minute phases (`*:M/N`, M≠0) that have no phase-less interval form.
    Calendar(Vec<CalEntry>),
}

/// Translate the OnCalendar subset the manifests actually use into a [`LaunchdSchedule`]:
/// `*:M/N` (every N minutes from minute M — phase 0 collapses to an interval, a non-zero phase to
/// per-minute calendar entries), `daily`, `*-*-* HH:MM:SS`, `*-*-* H/S:MM:SS` (hour-stepped), and
/// an optional `Www` / `Www..Www` weekday prefix on the dated forms. Anything else is an error —
/// better to refuse a schedule than silently fire at the wrong time.
pub fn launchd_schedule(on_calendar: &str) -> Result<LaunchdSchedule, String> {
    let s = on_calendar.trim();
    let unsupported = || format!("unsupported OnCalendar '{s}' for launchd");
    if s == "daily" {
        return Ok(LaunchdSchedule::Calendar(vec![CalEntry {
            weekday: None,
            hour: Some(0),
            minute: 0,
        }]));
    }
    // `*:M/N` — every N minutes starting at minute M within the hour. Phase 0 (`*:0/N`) is aligned
    // to the top of the hour, so it collapses to a plain repeat interval (`StartInterval`). A
    // non-zero phase (`*:15/30` → :15, :45) has no phase-offset interval form, so it becomes one
    // minute-only calendar entry per firing — launchd fires an omitted-Hour entry every hour at
    // that minute.
    if let Some((start, step)) = s.strip_prefix("*:").and_then(|r| r.split_once('/')) {
        let start: u8 = start.parse().map_err(|_| unsupported())?;
        let step: u64 = step.parse().map_err(|_| unsupported())?;
        if step == 0 || step > 59 || start > 59 {
            return Err(unsupported());
        }
        if start == 0 {
            return Ok(LaunchdSchedule::Interval(step * 60));
        }
        let entries = (start..60)
            .step_by(step as usize)
            .map(|minute| CalEntry {
                weekday: None,
                hour: None,
                minute,
            })
            .collect();
        return Ok(LaunchdSchedule::Calendar(entries));
    }

    // Optional weekday prefix, then `*-*-* <time>`.
    let (weekdays, rest) = match s.split_once(' ') {
        Some((first, rest))
            if first
                .chars()
                .next()
                .is_some_and(|c| c.is_ascii_alphabetic()) =>
        {
            let days: Vec<u8> = if let Some((a, b)) = first.split_once("..") {
                let (a, b) = (
                    weekday_num(a).ok_or_else(unsupported)?,
                    weekday_num(b).ok_or_else(unsupported)?,
                );
                if a > b {
                    return Err(unsupported());
                }
                (a..=b).collect()
            } else {
                vec![weekday_num(first).ok_or_else(unsupported)?]
            };
            (Some(days), rest)
        }
        _ => (None, s),
    };
    let time = rest.strip_prefix("*-*-* ").ok_or_else(unsupported)?;
    let parts: Vec<&str> = time.split(':').collect();
    let [h, m, _sec] = parts.as_slice() else {
        return Err(unsupported());
    };
    let minute: u8 = m.parse().map_err(|_| unsupported())?;
    // Hour: plain `HH`, or hour-stepped `H/S` (e.g. `0/6` → 0,6,12,18).
    let hours: Vec<u8> = if let Some((start, step)) = h.split_once('/') {
        let (start, step): (u8, u8) = (
            start.parse().map_err(|_| unsupported())?,
            step.parse().map_err(|_| unsupported())?,
        );
        if step == 0 {
            return Err(unsupported());
        }
        (start..24).step_by(step as usize).collect()
    } else {
        vec![h.parse().map_err(|_| unsupported())?]
    };
    if minute > 59 || hours.iter().any(|h| *h > 23) {
        return Err(unsupported());
    }

    let mut entries = Vec::new();
    for wd in weekdays.map_or(vec![None], |ds| ds.into_iter().map(Some).collect()) {
        for h in &hours {
            entries.push(CalEntry {
                weekday: wd,
                hour: Some(*h),
                minute,
            });
        }
    }
    Ok(LaunchdSchedule::Calendar(entries))
}

/// Render the launchd user-agent plist for one cron entry, following the hand-written
/// `jobs/launchd` conventions (login shell so `$HOME`/PATH resolve; `bn run` records the outcome).
/// launchd has no `RandomizedDelaySec`/network-online equivalent — those manifest fields are
/// simply not expressed; calendar firings missed while asleep coalesce to one run on wake (the
/// closest launchd gets to `Persistent=`). `Err` when the schedule doesn't translate.
pub fn render_launchd(rc: &ResolvedCron, bn_path: &str) -> Result<String, String> {
    let label = launchd_label(rc);
    let schedule = match launchd_schedule(&rc.entry.on_calendar)? {
        LaunchdSchedule::Interval(secs) => {
            format!("  <key>StartInterval</key>\n  <integer>{secs}</integer>\n")
        }
        LaunchdSchedule::Calendar(entries) => {
            let dict = |e: &CalEntry| {
                let wd = e
                    .weekday
                    .map(|w| format!("<key>Weekday</key><integer>{w}</integer>"))
                    .unwrap_or_default();
                // An omitted Hour is launchd's hourly wildcard — used by staggered minute phases
                // (`*:15/30` → :15/:45 of every hour).
                let hour = e
                    .hour
                    .map(|h| format!("<key>Hour</key><integer>{h}</integer>"))
                    .unwrap_or_default();
                format!(
                    "    <dict>{wd}{hour}<key>Minute</key><integer>{}</integer></dict>\n",
                    e.minute
                )
            };
            let body: String = entries.iter().map(dict).collect();
            format!("  <key>StartCalendarInterval</key>\n  <array>\n{body}  </array>\n")
        }
    };
    // `--` is illegal inside an XML comment (several manifest descriptions quote `--flags`).
    let desc = rc
        .entry
        .description
        .clone()
        .unwrap_or_else(|| format!("bn — {} (generated)", rc.entry.job))
        .replace("--", "-");
    Ok(format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n\
         <plist version=\"1.0\">\n\
         <dict>\n\
         \x20 <!-- {desc} — generated by `bn cron register` from {source}. -->\n\
         \x20 <key>Label</key>\n  <string>{label}</string>\n\
         \x20 <key>ProgramArguments</key>\n\
         \x20 <array>\n\
         \x20   <string>/bin/sh</string>\n\
         \x20   <string>-lc</string>\n\
         \x20   <string>exec \"{bn_path}\" run {job}</string>\n\
         \x20 </array>\n\
         {schedule}\
         \x20 <key>StandardOutPath</key>\n  <string>/tmp/{label}.log</string>\n\
         \x20 <key>StandardErrorPath</key>\n  <string>/tmp/{label}.log</string>\n\
         </dict>\n\
         </plist>\n",
        source = rc.source.display(),
        job = rc.entry.job,
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use bn_core::crons::{CronEntry, ResolvedCron};
    use bn_core::resolver::JobScope;

    fn rc(job: &str, on_calendar: &str) -> ResolvedCron {
        ResolvedCron {
            entry: CronEntry {
                job: job.into(),
                class: bn_core::crons::CronClass::Housekeeping,
                on_calendar: on_calendar.into(),
                only_on: vec![],
                description: None,
                persistent: true,
                randomized_delay: Some("2m".into()),
                network: true,
                catch_up: false,
            },
            scope: JobScope::Global,
            repo: None,
            source: "/x/crons.toml".into(),
        }
    }

    #[test]
    fn systemd_passes_oncalendar_through_and_wires_network() {
        let (svc, timer) = render_systemd(&rc("wt-cleanup", "*:0/15"), "/home/u/.bin/bn");
        assert!(svc.contains("ExecStart=/home/u/.bin/bn run wt-cleanup"));
        assert!(svc.contains("Wants=network-online.target"));
        assert!(timer.contains("OnCalendar=*:0/15"));
        assert!(timer.contains("Persistent=true"));
        assert!(timer.contains("RandomizedDelaySec=2m"));
        assert!(timer.contains("WantedBy=timers.target"));
    }

    #[test]
    fn systemd_renders_weekday_qualified_oncalendar_verbatim() {
        // Weekday-qualified specs are valid systemd grammar and pass straight through.
        let (_s, t) = render_systemd(&rc("standup-push", "Mon..Fri *-*-* 09:00:00"), "/b/bn");
        assert!(t.contains("OnCalendar=Mon..Fri *-*-* 09:00:00"));
    }

    #[test]
    fn repo_scope_names_unit_with_repo() {
        let mut r = rc("build", "daily");
        r.scope = JobScope::Repo;
        r.repo = Some("M365/Arena".into());
        assert_eq!(unit_name(&r), "bn-m365-arena-build");
    }

    #[test]
    fn launchd_label_and_job_round_trip() {
        assert_eq!(
            launchd_label(&rc("wt-cleanup", "daily")),
            "com.bn.wt-cleanup"
        );
        let mut r = rc("build", "daily");
        r.scope = JobScope::Repo;
        r.repo = Some("M365/Arena".into());
        assert_eq!(launchd_label(&r), "com.bn.m365-arena.build");
        assert_eq!(label_job("com.bn.wt-cleanup"), Some("wt-cleanup"));
        assert_eq!(label_job("com.bn.m365-arena.build"), Some("build"));
        assert_eq!(label_job("com.apple.finder"), None);
    }

    #[test]
    fn launchd_schedule_translates_every_manifest_form() {
        use LaunchdSchedule::*;
        // Minutely repeats → StartInterval.
        assert_eq!(launchd_schedule("*:0/15"), Ok(Interval(900)));
        assert_eq!(launchd_schedule("*:0/5"), Ok(Interval(300)));
        // Staggered minute phase `*:M/N` (M≠0) has no phase-less interval form, so it becomes one
        // minute-only calendar entry per firing (`{Minute:15},{Minute:45}`; an omitted Hour is
        // launchd's hourly wildcard). This is the #421 pr-observe repro.
        let Ok(Calendar(ph)) = launchd_schedule("*:15/30") else {
            panic!()
        };
        assert_eq!(
            ph.iter().map(|e| (e.hour, e.minute)).collect::<Vec<_>>(),
            [(None, 15), (None, 45)]
        );
        // Phase 0 still collapses to the interval shortcut.
        assert_eq!(launchd_schedule("*:0/30"), Ok(Interval(1800)));
        // daily → midnight.
        let Ok(Calendar(d)) = launchd_schedule("daily") else {
            panic!()
        };
        assert_eq!((d[0].hour, d[0].minute, d[0].weekday), (Some(0), 0, None));
        // Fixed time.
        let Ok(Calendar(t)) = launchd_schedule("*-*-* 07:00:00") else {
            panic!()
        };
        assert_eq!((t.len(), t[0].hour, t[0].minute), (1, Some(7), 0));
        // Hour-stepped → one entry per firing hour.
        let Ok(Calendar(h)) = launchd_schedule("*-*-* 0/6:00:00") else {
            panic!()
        };
        assert_eq!(
            h.iter().map(|e| e.hour).collect::<Vec<_>>(),
            [Some(0), Some(6), Some(12), Some(18)]
        );
        // Single weekday + range (Mon=1 … Fri=5).
        let Ok(Calendar(mon)) = launchd_schedule("Mon *-*-* 06:00:00") else {
            panic!()
        };
        assert_eq!((mon.len(), mon[0].weekday), (1, Some(1)));
        let Ok(Calendar(wk)) = launchd_schedule("Mon..Fri *-*-* 17:00:00") else {
            panic!()
        };
        assert_eq!(
            wk.iter().map(|e| e.weekday).collect::<Vec<_>>(),
            [Some(1), Some(2), Some(3), Some(4), Some(5)]
        );
        assert!(wk.iter().all(|e| e.hour == Some(17) && e.minute == 0));
    }

    #[test]
    fn launchd_schedule_rejects_what_it_cannot_express() {
        for bad in [
            "*:0/0",
            "*:0/75",
            "*:15/0",  // zero step
            "*:15/60", // step out of range
            "*:70/30", // minute phase out of range
            "hourly-ish",
            "2026-01-01 09:00:00",
            "Xxx *-*-* 09:00:00",
            "Fri..Mon *-*-* 09:00:00", // inverted range
            "*-*-* 09:00",             // missing seconds
        ] {
            assert!(launchd_schedule(bad).is_err(), "{bad} should be rejected");
        }
    }

    #[test]
    fn launchd_plist_renders_exec_schedule_and_sanitized_comment() {
        let mut r = rc("attention-sync", "*:0/5");
        r.entry.description = Some("bn — attention-sync -> `bn next --refresh`".into());
        let plist = render_launchd(&r, "/Users/u/.config/bn/bn").unwrap();
        assert!(plist.contains("<string>com.bn.attention-sync</string>"));
        assert!(plist.contains("exec \"/Users/u/.config/bn/bn\" run attention-sync"));
        assert!(plist.contains("<key>StartInterval</key>\n  <integer>300</integer>"));
        // `--` never survives into the XML comment (it's illegal there).
        assert!(!plist.contains("--refresh"), "comment must be XML-safe");

        let cal = render_launchd(&rc("standup-push", "Mon..Fri *-*-* 09:00:00"), "/b/bn").unwrap();
        assert!(cal.contains("StartCalendarInterval"));
        assert_eq!(cal.matches("<key>Weekday</key>").count(), 5);

        assert!(render_launchd(&rc("x", "not-a-schedule"), "/b/bn").is_err());
    }

    #[test]
    fn info_gather_manifest_entry_renders_for_all_backends() {
        // The ten per-info timers (pr-queue, meetings, quarter-review, …) collapsed into ONE
        // shipped `info-gather` cron; each agent's own schedule now drives its cadence in-process
        // (see `crate::cmd::cron::job_info_gather`). That single entry must still generate valid
        // artifacts for BOTH backends `bn cron register` targets — systemd (verbatim OnCalendar)
        // and launchd (translated) — so the WSL/Windows systemd-in-WSL path wires it too. This is
        // the successor of the retired quarter-review-specific guard.
        let manifest = concat!(env!("CARGO_MANIFEST_DIR"), "/../../config/crons.toml");
        let entries = bn_core::crons::parse_manifest(std::path::Path::new(manifest))
            .expect("config/crons.toml parses");
        let ig = entries
            .iter()
            .find(|e| e.job == "info-gather")
            .expect("config/crons.toml must declare the single info-gather cron");
        let resolved = ResolvedCron {
            entry: ig.clone(),
            scope: JobScope::Global,
            repo: None,
            source: manifest.into(),
        };
        let (svc, timer) = render_systemd(&resolved, "/home/u/.bin/bn");
        assert!(svc.contains("ExecStart=/home/u/.bin/bn run info-gather"));
        assert!(timer.contains(&format!("OnCalendar={}", ig.on_calendar)));
        assert!(
            render_launchd(&resolved, "/home/u/.bin/bn").is_ok(),
            "info-gather schedule '{}' must translate for launchd",
            ig.on_calendar
        );
    }

    #[test]
    fn launchd_plist_renders_staggered_minute_phase_without_hour() {
        // #421: the shipped `pr-observe` cron (`*:15/30`) must render minute-only calendar entries
        // — fire at :15/:45 of every hour — as a StartCalendarInterval, NOT a StartInterval, and
        // with NO Hour key (an omitted Hour is launchd's hourly wildcard).
        let plist = render_launchd(&rc("pr-observe", "*:15/30"), "/Users/u/.bin/bn").unwrap();
        assert!(plist.contains("<key>StartCalendarInterval</key>"));
        assert!(
            !plist.contains("<key>StartInterval</key>"),
            "a phased minute is calendar-scheduled, not a plain interval"
        );
        assert!(
            !plist.contains("<key>Hour</key>"),
            "minute-only entries must omit Hour so they fire every hour"
        );
        assert_eq!(plist.matches("<key>Minute</key>").count(), 2);
        assert!(plist.contains("<key>Minute</key><integer>15</integer>"));
        assert!(plist.contains("<key>Minute</key><integer>45</integer>"));
    }

    #[test]
    fn every_shipped_cron_translates_for_launchd() {
        // #421 regression guard: every entry in the shipped config/crons.toml must translate to a
        // launchd schedule — an untranslatable form is silently dropped on macOS (as pr-observe's
        // `*:15/30` was). systemd takes OnCalendar verbatim, so launchd is the strict backend.
        let manifest = concat!(env!("CARGO_MANIFEST_DIR"), "/../../config/crons.toml");
        let entries = bn_core::crons::parse_manifest(std::path::Path::new(manifest))
            .expect("config/crons.toml parses");
        for e in &entries {
            assert!(
                launchd_schedule(&e.on_calendar).is_ok(),
                "shipped cron '{}' schedule '{}' must translate for launchd",
                e.job,
                e.on_calendar
            );
        }
    }
}
